def _safe_upload_name(original: str) -> str:
    """生成安全的素材文件名。

    werkzeug 的 secure_filename 只保留 ASCII：纯中文名 "上传测试视频.mp4" 会被清成 "mp4"
    ——连点都没了，扩展名直接丢失，后续 ffmpeg 抽帧和平台上传都会失败。
    所以策略是：清洗后如果拿不到合法的"主名.扩展名"，就退化成时间戳名并保留原扩展名。
    """
    original = (original or "").strip()
    ext = Path(original).suffix.lower()
    if not re.fullmatch(r"\.[a-z0-9]{1,6}", ext or ""):
        ext = ".mp4"
    cleaned = secure_filename(original)
    if cleaned and cleaned.lower().endswith(ext) and Path(cleaned).stem:
        return cleaned
    return f"video_{time.strftime('%Y%m%d_%H%M%S')}{ext}"


@app.route('/upload', methods=['POST'])
def upload_file():
    if 'file' not in request.files:
        return jsonify({
            "code": 400,
            "data": None,
            "msg": "No file part in the request"
        }), 400
    file = request.files['file']
    if file.filename == '':
        return jsonify({
            "code": 400,
            "data": None,
            "msg": "No selected file"
        }), 400
    try:
        # 保存文件到指定位置
        uuid_v1 = uuid.uuid1()
        print(f"UUID v1: {uuid_v1}")
        safe_name = _safe_upload_name(file.filename)
        filepath = Path(BASE_DIR / "videoFile" / f"{uuid_v1}_{safe_name}")
        # 上游缺少这一步：全新安装时 videoFile/ 目录不存在，file.save() 会直接抛
        # FileNotFoundError，表现为前端"选择本地视频后报错"。这里补上建目录。
        filepath.parent.mkdir(parents=True, exist_ok=True)
        file.save(filepath)

        # 上游也漏了这一步：/upload 只存文件、不写 file_records，
        # 导致"素材管理"页面看不到这里上传的文件（只有 /uploadSave 会写库）。
        # 补上记录，两个入口行为就一致了。
        disk_name = f"{uuid_v1}_{safe_name}"
        try:
            with sqlite3.connect(Path(BASE_DIR / "db" / "database.db")) as conn:
                conn.execute(
                    "INSERT INTO file_records (filename, filesize, file_path) VALUES (?, ?, ?)",
                    (safe_name, round(filepath.stat().st_size / (1024 * 1024), 2), disk_name),
                )
                conn.commit()
        except Exception as db_exc:
            # 记库失败不影响上传本身，但要说清楚，免得又出现"文件在、列表里没有"
            print(f"⚠️ 上传成功但写入 file_records 失败（素材管理里可能看不到）: {db_exc}")

        return jsonify({"code":200,"msg": "File uploaded successfully", "data": disk_name}), 200
    except Exception as e:
        return jsonify({"code":500,"msg": str(e),"data":None}), 500

