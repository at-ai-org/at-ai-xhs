# 包装函数：在线程中运行异步函数
def run_async_function(type, id, status_queue):
    """跑各平台的扫码登录。

    必须兜住所有异常：这个函数跑在后台线程里，一旦抛异常线程就静默死掉，
    SSE 队列永远是空的，前端就会一直转圈——这正是"一直加载中"的成因之一。
    所以任何失败都要往队列里塞一个 500，让界面明确报错。
    """
    try:
        _run_login_task(type, id, status_queue)
    except Exception as exc:
        import traceback
        traceback.print_exc()
        print(f"❌ 登录流程异常（{type}/{id}）: {exc}")
        status_queue.put("500")


def _run_login_task(type, id, status_queue):
    match type:
        case '1':
            loop = asyncio.new_event_loop()
            asyncio.set_event_loop(loop)
            loop.run_until_complete(xiaohongshu_cookie_gen(id, status_queue))
            loop.close()
        case '2':
            loop = asyncio.new_event_loop()
            asyncio.set_event_loop(loop)
            loop.run_until_complete(get_tencent_cookie(id,status_queue))
            loop.close()
        case '3':
            loop = asyncio.new_event_loop()
            asyncio.set_event_loop(loop)
            loop.run_until_complete(douyin_cookie_gen(id,status_queue))
            loop.close()
        case '4':
            loop = asyncio.new_event_loop()
            asyncio.set_event_loop(loop)
            loop.run_until_complete(get_ks_cookie(id,status_queue))
            loop.close()
        case _:
            print(f"⚠️ 未知的登录类型: {type!r}")
            status_queue.put("500")

# SSE 流生成器函数
def sse_stream(status_queue):
    while True:
        if not status_queue.empty():
            msg = status_queue.get()
            yield f"data: {msg}\n\n"
        else:
            # 避免 CPU 占满
            time.sleep(0.1)

